# -*- coding: utf-8 -*-
"""
ESP32 空气质量检测仪 —— 全局配置
================================================================
所有需要按自己的硬件修改的内容都集中在本文件, 其它文件一般不用改。

硬件清单
    MCU      : ESP32 经典款 (ESP32-WROOM-32 / ESP32 DevKitC)
    显示屏   : 1.2 寸 OLED, 128x64, I2C (SSD1306 或 SH1106)
    温湿度   : SHT40   (I2C, 地址 0x44)
    TVOC     : SGP40   (I2C, 地址 0x59)
    二氧化碳 : SCD40   (I2C, 地址 0x62)
    甲醛     : ZE08-CH2O (UART, 9600 8N1)

接线请看项目根目录 README.md 的“接线表”。
"""

VERSION = "1.0.0"
BOARD = "ESP32-GENERIC"

# --------------------------------------------------------------------------
# 1. 调试
# --------------------------------------------------------------------------
# True  : 通过 USB 串口(REPL) 打印运行日志, 便于排查问题
# False : 安静模式, 只驱动屏幕
DEBUG = True
# 打印 I2C 扫描结果
DEBUG_SCAN = True

# --------------------------------------------------------------------------
# 2. I2C 总线
#     OLED / SHT40 / SGP40 / SCD40 四者共用一条 I2C 总线
#     它们的地址互不冲突, 可以并联在同一组 SDA/SCL 上
# --------------------------------------------------------------------------
I2C_ID = 0
# 本板子的排针没有引出 GPIO21, 所以 I2C 改用 GPIO32/33。
# 这两个脚不与本项目其它外设(GPIO2/16/17/25/27)冲突。
I2C_SDA = 32            # GPIO32 -> 所有 I2C 模块的 SDA
I2C_SCL = 33            # GPIO33 -> 所有 I2C 模块的 SCL
I2C_FREQ = 400000       # 400kHz 快速模式

# --------------------------------------------------------------------------
# 3. OLED 显示屏
# --------------------------------------------------------------------------
OLED_ENABLED = True

# 控制器型号:
#   "ssd1306" —— 绝大多数 0.96 寸 / 1.2 寸 128x64 模块
#   "sh1106"  —— 部分 1.3 寸 / 早期 1.2 寸 128x64 模块
# 如果屏幕点不亮, 或者整幅图像向右错位 2 个像素, 就把这里改成 "sh1106"。
# 也可以用工具脚本在线判断: python tools/deploy.py run test_oled
OLED_CONTROLLER = "ssd1306"

OLED_WIDTH = 128
OLED_HEIGHT = 64
OLED_ADDR = 0x3C        # 极少数模块是 0x3D
OLED_CONTRAST = 0xFF    # 0~255 亮度
OLED_ROTATE = False     # True 表示 180° 翻转

# 屏幕刷新周期 (毫秒)
UI_PERIOD_MS = 250

# --------------------------------------------------------------------------
# 4. I2C 传感器地址
# --------------------------------------------------------------------------
SHT40_ADDR = 0x44       # SHT40 默认地址, ADDR 引脚拉高则为 0x45
SGP40_ADDR = 0x59       # SGP40 固定地址
SCD40_ADDR = 0x62       # SCD40 固定地址

# 各传感器是否启用 (单独测试某个传感器时可以只留一个 True)
SHT40_ENABLED = True
SGP40_ENABLED = True
SCD40_ENABLED = True

# --------------------------------------------------------------------------
# 5. ZE08-CH2O 甲醛传感器 (UART)
# --------------------------------------------------------------------------
ZE08_ENABLED = True
ZE08_UART_ID = 2
ZE08_TX = 17            # ESP32 的 TX (GPIO17) -> ZE08 的 RXD
ZE08_RX = 16            # ESP32 的 RX (GPIO16) <- ZE08 的 TXD
ZE08_BAUD = 9600        # 出厂固定 9600 8N1

# --------------------------------------------------------------------------
# 6. 指示灯 / 按键 / 蜂鸣器 (不需要可以关掉)
# --------------------------------------------------------------------------
STATUS_LED = 2                  # 板载蓝色 LED (ESP32 DevKitC); 无则填 None
STATUS_LED_ACTIVE_LOW = False   # 板载 LED 低电平点亮时改 True

BUTTON_ENABLED = True           # 接一个按键到 GND, 用于翻页/消音
BUTTON_PIN = 27                 # 内部上拉, 按下为低电平

BUZZER_ENABLED = False          # 有源蜂鸣器, 报警时鸣叫
BUZZER_PIN = 25


# --------------------------------------------------------------------------
# 7. 上电预热时间 (秒)
# --------------------------------------------------------------------------
# 预热的含义: 传感器已连上、也在正常通信, 但读数还没到可信状态。
# 预热期间屏幕上会显示专门的“预热中”标记和倒计时。
#
# 依据 (详见 README.md 的说明):
#   SHT40   几乎不需要预热, 上电后第一次测量即可用
#   SCD40   上电约 5s 出第一个数, 30s 后进入数据手册标称精度
#   ZE08    数据手册标明 预热时间 <= 3 分钟
#   SGP40   算法前 45s 为 blackout, 约 1 小时才完全收敛到最佳状态
#           这里取 60s 作为“可读数”的门限, 1 小时内屏幕右上角仍会显示
#           “学习”标记 (~), 表示 VOC 指数还在自我学习基线
WARMUP_SHT40 = 1
WARMUP_SCD40 = 30
WARMUP_ZE08 = 180
WARMUP_SGP40 = 60

# SGP40 VOC 算法的完整学习时间(秒), 仅用于在屏幕上显示“学习期”标记
VOC_LEARN_S = 3600

# --------------------------------------------------------------------------
# 8. 报警阈值
# --------------------------------------------------------------------------
# 甲醛限值参考 GB/T 18883-2022《室内空气质量标准》: 0.08 mg/m3 (1小时均值)
HCHO_WARN = 0.08        # mg/m3
HCHO_ALARM = 0.10       # mg/m3

# CO2: 1000ppm 以上表示通风不足, 1500ppm 以上明显不适
CO2_WARN = 1000         # ppm
CO2_ALARM = 1500        # ppm

# VOC 指数 (Sensirion 定义): 100 为基线, 越大空气越差
TVOC_WARN = 150
TVOC_ALARM = 250

# --------------------------------------------------------------------------
# 9. 采样 / 轮询周期
# --------------------------------------------------------------------------
# I2C 传感器的主轮询周期 (毫秒)
I2C_POLL_MS = 1000
# 每 N 次主轮询读取一次 SCD40 (SCD40 内部测量周期为 5s)
SCD40_EVERY = 5
# 断开/未连接传感器的重新探测周期 (毫秒) —— 支持运行中热插拔传感器
RESCAN_MS = 10000

# LED / 蜂鸣器
LED_HEARTBEAT_MS = 2000
